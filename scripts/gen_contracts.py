#!/usr/bin/env python3
"""Generate the published contracts from the Pydantic source of truth (PLAN_V2 D18, §11.3a).

    cd vision && uv run --no-sync python ../scripts/gen_contracts.py            # write in place
    cd vision && uv run --no-sync python ../scripts/gen_contracts.py --check    # exit 1 if anything is stale
    cd vision && uv run --no-sync python ../scripts/gen_contracts.py --out-dir /tmp/x

Writes:
  shared/spec/<name>.schema.json   one per vision/app/spec module, via TypeAdapter(...).json_schema(mode="serialization")
  web/src/core/types.gen.ts        ONE file: every exported type via json-schema-to-typescript (json2ts, pinned
                                   devDependency in web/), plus the embedded level schema for core.validateLevel().
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[1]
VISION = REPO / "vision"
WEB = REPO / "web"
SPEC_OUT = REPO / "shared" / "spec"
TYPES_OUT = WEB / "src" / "core" / "types.gen.ts"

if str(VISION) not in sys.path:
    sys.path.insert(0, str(VISION))

from pydantic import TypeAdapter  # noqa: E402
from pydantic.json_schema import GenerateJsonSchema  # noqa: E402

from app.spec import SCHEMA_MODULES, SPEC_VERSION  # noqa: E402

SCHEMA_ID = "https://draw-a-level.dev/spec/v2/{name}.schema.json"
BANNER = (
    "/* eslint-disable */\n"
    "/**\n"
    " * GENERATED by scripts/gen_contracts.py from vision/app/spec (Pydantic, the source of truth).\n"
    " * Do not edit. Change the Pydantic models through a contract PR (docs/v2/CONTRACTS.md), then regenerate:\n"
    " *   cd vision && uv run --no-sync python ../scripts/gen_contracts.py\n"
    " */"
)


class _Gen(GenerateJsonSchema):
    # Property titles ("Kind", "Opt", ...) would become junk named types in TS and add nothing to the spec.
    def field_title_should_be_set(self, schema: Any) -> bool:  # noqa: ARG002
        return False


def _name(t: Any) -> str:
    return getattr(t, "__name__", None) or str(t)


def _merge_def(defs: dict[str, Any], key: str, value: dict[str, Any], where: str) -> None:
    if key in defs and defs[key] != value:
        raise SystemExit(f"conflicting definitions for {key!r} ({where}); give the types distinct names")
    defs[key] = value


def module_schema(name: str, module: Any) -> dict[str, Any]:
    defs: dict[str, Any] = {}
    for t in module.EXPORTS:
        s = TypeAdapter(t).json_schema(mode="serialization", schema_generator=_Gen, ref_template="#/$defs/{model}")
        for k, v in s.pop("$defs", {}).items():
            _merge_def(defs, k, v, f"{name}:{_name(t)}")
        if set(s) != {"$ref"}:
            _merge_def(defs, _name(t), s, f"{name}:{_name(t)}")
    doc_line = (module.__doc__ or "").strip().splitlines()[0] if module.__doc__ else name
    out: dict[str, Any] = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": SCHEMA_ID.format(name=name),
        "$comment": f"dal-level spec v{SPEC_VERSION}. GENERATED from vision/app/spec/{module.__name__.rsplit('.', 1)[-1]}.py "
        "by scripts/gen_contracts.py; do not edit.",
        "title": name,
        "description": doc_line,
    }
    if module.ROOT is not None:
        out["$ref"] = f"#/$defs/{_name(module.ROOT)}"
    out["$defs"] = dict(sorted(defs.items()))
    return out


def all_schemas() -> dict[str, dict[str, Any]]:
    return {name: module_schema(name, mod) for name, mod in SCHEMA_MODULES.items()}


def _ts_friendly(node: Any) -> Any:
    """Rewrite JSON Schema 2020-12 bits json2ts does not understand (tuples, extension keys)."""
    if isinstance(node, list):
        return [_ts_friendly(x) for x in node]
    if not isinstance(node, dict):
        return node
    out: dict[str, Any] = {}
    for k, v in node.items():
        if k in ("patternProperties", "discriminator", "$schema", "$id", "$comment", "default"):
            continue  # x_* keys are ignored by engines; defaults are runtime, not type, information
        if k == "prefixItems":
            out["items"] = _ts_friendly(v)
            continue
        out[k] = _ts_friendly(v)
    return out


def combined_ts_schema(schemas: dict[str, dict[str, Any]]) -> dict[str, Any]:
    defs: dict[str, Any] = {}
    for name, s in schemas.items():
        for k, v in s["$defs"].items():
            _merge_def(defs, k, v, name)
    return _ts_friendly({
        "title": "DalSpecIndex",
        "description": "Index of every contract type (generated; carries no data).",
        "type": "object",
        "properties": {},
        "additionalProperties": False,
        "$defs": dict(sorted(defs.items())),
    })


_REF_NOTE = r" \* This interface was referenced by `DalSpecIndex`'s JSON-Schema\n \* via the `definition` \"[^\"]+\"\.\n"


def _tidy_ts(ts: str) -> str:
    """Drop json2ts's per-definition provenance notes and the empty index interface."""
    ts = re.sub(r"/\*\*\n" + _REF_NOTE + r" \*/\n", "", ts)
    ts = re.sub(r" \*\n" + _REF_NOTE, "", ts)
    ts = re.sub(r"/\*\*\n \* Index of every contract type[^\n]*\n \*/\nexport interface DalSpecIndex \{\}\n", "", ts)
    return ts


def render_types(schemas: dict[str, dict[str, Any]], work: Path) -> str:
    src = work / "dal_spec_combined.json"
    out = work / "types.gen.ts"
    src.write_text(json.dumps(combined_ts_schema(schemas), indent=1))
    cmd = [
        "npx", "--no-install", "--prefix", str(WEB), "json2ts",
        "-i", str(src), "-o", str(out),
        "--additionalProperties", "false", "--unreachableDefinitions", "--bannerComment", BANNER,
    ]
    proc = subprocess.run(cmd, cwd=REPO, capture_output=True, text=True)
    if proc.returncode != 0:
        raise SystemExit(f"json2ts failed ({proc.returncode}):\n{proc.stderr or proc.stdout}")
    ts = _tidy_ts(out.read_text())
    level = schemas["level"]
    appendix = (
        "\n/** Contract version of the generated types. */\n"
        f"export const SPEC_VERSION = {json.dumps(SPEC_VERSION)};\n"
        "\n/** shared/spec/level.schema.json, embedded so core.validateLevel() needs no JSON import. */\n"
        f"export const LEVEL_SCHEMA: Record<string, unknown> = {json.dumps(level, separators=(',', ':'), ensure_ascii=False)};\n"
    )
    return ts.rstrip("\n") + "\n" + appendix


def generate(spec_dir: Path, types_path: Path) -> list[Path]:
    schemas = all_schemas()
    spec_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for name, s in schemas.items():
        p = spec_dir / f"{name}.schema.json"
        p.write_text(json.dumps(s, indent=2, ensure_ascii=False) + "\n")
        written.append(p)
    with tempfile.TemporaryDirectory(prefix="dal_contracts_") as tmp:
        types_path.parent.mkdir(parents=True, exist_ok=True)
        types_path.write_text(render_types(schemas, Path(tmp)))
    written.append(types_path)
    return written


def check() -> list[str]:
    """Regenerate into a temp dir and diff against the committed files. Returns stale paths."""
    stale: list[str] = []
    with tempfile.TemporaryDirectory(prefix="dal_contracts_check_") as tmp:
        t = Path(tmp)
        generate(t / "spec", t / "types.gen.ts")
        for p in sorted((t / "spec").glob("*.schema.json")):
            committed = SPEC_OUT / p.name
            if not committed.exists() or committed.read_text() != p.read_text():
                stale.append(str(committed.relative_to(REPO)))
        expected = {p.name for p in (t / "spec").glob("*.schema.json")}
        for p in sorted(SPEC_OUT.glob("*.schema.json")):
            if p.name not in expected:
                stale.append(f"{p.relative_to(REPO)} (no longer generated)")
        if not TYPES_OUT.exists() or TYPES_OUT.read_text() != (t / "types.gen.ts").read_text():
            stale.append(str(TYPES_OUT.relative_to(REPO)))
    return stale


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if a generated file is stale")
    ap.add_argument("--out-dir", type=Path, help="write <dir>/spec/*.schema.json and <dir>/types.gen.ts instead")
    a = ap.parse_args()
    if a.check:
        stale = check()
        if stale:
            print("stale generated contracts (run scripts/gen_contracts.py):\n  " + "\n  ".join(stale))
            return 1
        print("contracts are fresh")
        return 0
    if a.out_dir:
        files = generate(a.out_dir / "spec", a.out_dir / "types.gen.ts")
    else:
        files = generate(SPEC_OUT, TYPES_OUT)
    for f in files:
        print("wrote", f)
    return 0


if __name__ == "__main__":
    sys.exit(main())
