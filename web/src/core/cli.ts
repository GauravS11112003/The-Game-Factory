/// <reference types="node" />
/**
 * Core CLI (lane B). Runs natively on Node 24:  node web/src/core/cli.ts <command>
 *
 *   selftest [--real]   core rules + contracts + worker round trip. Default (stub mode, P0 gate): functions that
 *                       still throw NotImplemented are reported, not failed. --real (P1 gate) fails on any stub.
 *   gen-spec-data       write shared/spec/params.json and shared/spec/physics-profiles.json from params.ts / profiles
 *   hash <level.json>   print level_hash
 *   validate <file>     run validateLevel and print the verdict
 *   fixture <method>    print the DAL_CORE_STUB canned result for a worker method (used to build sample streams)
 *   golden | starter:build | starter:verify | calibrate | envelope | bench   (land in P1-P4)
 */
import { spawn } from 'node:child_process';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import * as core from './index.ts';
import { PARAMS } from './params.ts';
import { canonicalJson } from './util/canonical.ts';
import { isNotImplemented } from './util/errors.ts';
import { lintSource } from './util/lint.ts';
import { sha256Hex } from './util/sha256.ts';
import { stubResult } from './worker/stub.ts';
import type { LevelV2, ProfileId, WorkerMethod } from './types.gen.ts';

const CORE_DIR = dirname(fileURLToPath(import.meta.url));
const REPO = join(CORE_DIR, '..', '..', '..');
const SPEC_DIR = join(REPO, 'shared', 'spec');
const LEVELS_DIR = join(SPEC_DIR, 'conformance', 'levels');

function walk(dir: string): string[] {
  const out: string[] = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else if (name.endsWith('.ts')) out.push(p);
  }
  return out.sort();
}

export function coreFiles(): string[] {
  return walk(CORE_DIR).map((p) => relative(CORE_DIR, p).split('\\').join('/'));
}

function readJson(p: string): unknown {
  return JSON.parse(readFileSync(p, 'utf8'));
}

function specData(): Record<string, string> {
  const profiles = Object.fromEntries(
    Object.entries(core.PROFILES).map(([id, p]) => [id, { ...p, profile_hash: core.profileHash(id as ProfileId) }]),
  );
  return {
    'params.json': JSON.stringify({ $comment: 'GENERATED by `node web/src/core/cli.ts gen-spec-data` from web/src/core/params.ts; normative. Do not edit.', core_version: core.CORE_VERSION, ...PARAMS }, null, 2) + '\n',
    'physics-profiles.json': JSON.stringify({ $comment: 'GENERATED by `node web/src/core/cli.ts gen-spec-data` from web/src/core/sim/profiles.ts; normative, immutable by name.', profiles }, null, 2) + '\n',
  };
}

// ---- selftest ------------------------------------------------------------------------------------

interface Check {
  name: string;
  run: () => Promise<string | void> | string | void;
}

class Stub extends Error {}

/** Dummy arguments per API function, used only to observe whether the function is still a stub. */
function probeArgs(fn: string): unknown[] {
  const level = readJson(join(LEVELS_DIR, 'valid', 'minimal_1screen.json')) as LevelV2;
  switch (fn) {
    case 'levelHash':
    case 'validateLevel':
    case 'migrateV1':
      return [level];
    case 'encodeReplay':
      return [Uint8Array.from([0, 0, 2])];
    case 'decodeReplay':
      return ['AgAAAQAC'];
    case 'analyze':
      return [level, { mode: 'fast' }];
    default:
      return [level, level, level, level, level];
  }
}

async function workerRoundTrip(stub: boolean): Promise<string> {
  const child = spawn(process.execPath, [join(CORE_DIR, 'worker', 'main.ts')], {
    cwd: REPO,
    env: { ...process.env, DAL_CORE_STUB: stub ? '1' : '0' },
    stdio: ['pipe', 'pipe', 'inherit'],
  });
  const lines: string[] = [];
  let buf = '';
  const done = new Promise<void>((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error('worker did not answer within 5 s')), 5000);
    child.stdout.on('data', (d: Buffer) => {
      buf += d.toString('utf8');
      let i: number;
      while ((i = buf.indexOf('\n')) >= 0) {
        lines.push(buf.slice(0, i));
        buf = buf.slice(i + 1);
      }
      if (lines.length >= 2) {
        clearTimeout(timer);
        resolve();
      }
    });
    child.on('error', reject);
  });
  child.stdin.write(JSON.stringify({ id: 1, method: 'ping', params: {} }) + '\n');
  child.stdin.write(JSON.stringify({ id: 2, method: 'level_hash', params: { level: readJson(join(LEVELS_DIR, 'valid', 'minimal_1screen.json')) } }) + '\n');
  await done;
  child.stdin.end();
  const [ping, hash] = lines.map((l) => JSON.parse(l));
  if (!ping.ok || ping.result.core_version !== core.CORE_VERSION) throw new Error(`bad ping: ${lines[0]}`);
  if (!hash.ok || !String(hash.result.hash).startsWith('sha256:')) throw new Error(`bad level_hash: ${lines[1]}`);
  return `${ping.result.node}, stub=${ping.result.stub}`;
}

async function selftest(real: boolean): Promise<number> {
  const stubs: string[] = [];
  const checks: Check[] = [
    {
      name: 'node >= 24',
      run: () => {
        const major = Number(process.versions.node.split('.')[0]);
        if (major < 24) throw new Error(`node ${process.version}`);
        return process.version;
      },
    },
    {
      name: 'core lint (.ts suffixes, no npm/DOM/Phaser/JSON imports, determinism bans)',
      run: () => {
        const files = coreFiles();
        const issues = files.flatMap((f) => lintSource(f, readFileSync(join(CORE_DIR, f), 'utf8')));
        if (issues.length) throw new Error(issues.slice(0, 10).map((i) => `${i.file}:${i.line} ${i.rule}: ${i.text}`).join('\n'));
        return `${files.length} files`;
      },
    },
    {
      name: 'every core module imports natively (catches value imports of types)',
      run: async () => {
        const skip = new Set(['cli.ts', 'worker/main.ts', 'worker/web.worker.ts']);
        const mods = coreFiles().filter((f) => !skip.has(f) && !f.startsWith('__tests__/'));
        for (const f of mods) await import(pathToFileURL(join(CORE_DIR, f)).href);
        return `${mods.length} modules`;
      },
    },
    {
      name: 'API exports every §11.3(b) function',
      run: () => {
        const exported = core as unknown as Record<string, unknown>;
        const missing = core.API_FUNCTIONS.filter((fn) => typeof exported[fn] !== 'function');
        if (missing.length) throw new Error(`missing: ${missing.join(', ')}`);
        if (typeof core.PROFILES !== 'object') throw new Error('PROFILES missing');
        for (const fn of core.API_FUNCTIONS) {
          try {
            (exported[fn] as (...a: unknown[]) => unknown)(...probeArgs(fn));
          } catch (e) {
            if (isNotImplemented(e)) stubs.push(fn);
          }
        }
        const p0Stubbed = core.P0_REAL.filter((fn) => stubs.includes(fn));
        if (p0Stubbed.length) throw new Error(`must be real at P0: ${p0Stubbed.join(', ')}`);
        if (real && stubs.length) throw new Stub(`still stubs: ${stubs.join(', ')}`);
        return `${core.API_FUNCTIONS.length} functions, ${stubs.length} stubs`;
      },
    },
    {
      name: 'sha256 + canonical JSON vectors',
      run: () => {
        const v: [string, string][] = [
          ['', 'e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855'],
          ['abc', 'ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad'],
          ['é✓🙂', sha256Hex(Uint8Array.from([0xc3, 0xa9, 0xe2, 0x9c, 0x93, 0xf0, 0x9f, 0x99, 0x82]))],
        ];
        for (const [input, want] of v) if (sha256Hex(input) !== want) throw new Error(`sha256(${JSON.stringify(input)})`);
        const c = canonicalJson({ b: 2.0, a: [1.23456, -0.00004, 0.00005, 1e-9, 7.1], n: null, s: 'x"y' });
        if (c !== '{"a":[1.2346,0,0.0001,0,7.1],"b":2,"s":"x\\"y"}') throw new Error(`canonical: ${c}`);
      },
    },
    {
      name: 'conformance levels: validateLevel + level_hash',
      run: () => {
        let n = 0;
        for (const f of readdirSync(join(LEVELS_DIR, 'valid'))) {
          const lv = readJson(join(LEVELS_DIR, 'valid', f)) as LevelV2;
          const r = core.validateLevel(lv);
          if (!r.ok) throw new Error(`valid/${f}: ${r.errors[0]}`);
          if (/^sha256:[0-9a-f]{64}$/.test(lv.meta.level_hash) && core.levelHash(lv) !== lv.meta.level_hash) {
            throw new Error(`valid/${f}: level_hash ${core.levelHash(lv)} != ${lv.meta.level_hash}`);
          }
          n++;
        }
        for (const f of readdirSync(join(LEVELS_DIR, 'invalid'))) {
          if (core.validateLevel(readJson(join(LEVELS_DIR, 'invalid', f))).ok) throw new Error(`invalid/${f} was accepted`);
          n++;
        }
        return `${n} files`;
      },
    },
    {
      name: 'replay codec round trip',
      run: () => {
        const frames = new Uint8Array(70000);
        for (let i = 0; i < frames.length; i++) frames[i] = i < 66000 ? 2 : (i >> 4) & 31;
        const back = core.decodeReplay(core.encodeReplay(frames));
        if (back.length !== frames.length || back.some((b, i) => b !== frames[i])) throw new Error('mismatch');
      },
    },
    {
      name: 'physics profiles',
      run: () => {
        const ids: ProfileId[] = ['v2-standard', 'v2-gentle', 'v2-snappy', 'v1-classic'];
        for (const id of ids) if (core.PROFILES[id]?.id !== id) throw new Error(`profile ${id}`);
        return core.profileHash('v2-standard');
      },
    },
    {
      name: 'shared/spec params.json + physics-profiles.json are fresh',
      run: () => {
        for (const [name, text] of Object.entries(specData())) {
          let have = '';
          try {
            have = readFileSync(join(SPEC_DIR, name), 'utf8');
          } catch {
            /* missing */
          }
          if (have !== text) throw new Error(`${name} is stale: run node web/src/core/cli.ts gen-spec-data`);
        }
      },
    },
    { name: 'worker round trip (real mode)', run: () => workerRoundTrip(false) },
    { name: 'worker round trip (DAL_CORE_STUB=1)', run: () => workerRoundTrip(true) },
  ];

  let failed = 0;
  for (const c of checks) {
    try {
      const note = await c.run();
      console.log(`ok    ${c.name}${note ? `  (${note})` : ''}`);
    } catch (e) {
      failed++;
      console.log(`FAIL  ${c.name}\n      ${e instanceof Error ? e.message.split('\n').join('\n      ') : String(e)}`);
    }
  }
  if (stubs.length) console.log(`stub  ${stubs.join(', ')}`);
  console.log(failed ? `selftest FAILED (${failed})` : `selftest passed (${real ? 'real' : 'stub'} mode)`);
  return failed ? 1 : 0;
}

// ---- entry ----------------------------------------------------------------------------------

async function main(argv: string[]): Promise<number> {
  const [cmd, ...rest] = argv;
  switch (cmd) {
    case 'selftest':
      return selftest(rest.includes('--real') || process.env.DAL_CORE_REAL === '1');
    case 'gen-spec-data':
      for (const [name, text] of Object.entries(specData())) {
        writeFileSync(join(SPEC_DIR, name), text);
        console.log(`wrote shared/spec/${name}`);
      }
      return 0;
    case 'hash':
      console.log(core.levelHash(readJson(rest[0]) as LevelV2));
      return 0;
    case 'validate': {
      const r = core.validateLevel(readJson(rest[0]));
      console.log(r.ok ? 'valid' : r.errors.join('\n'));
      return r.ok ? 0 : 1;
    }
    case 'fixture':
      console.log(JSON.stringify(stubResult(rest[0] as WorkerMethod, rest[1] ? (JSON.parse(rest[1]) as Record<string, unknown>) : {})));
      return 0;
    case 'golden':
    case 'starter:build':
    case 'starter:verify':
    case 'calibrate':
    case 'envelope':
    case 'bench':
      console.error(`cli.ts ${cmd}: not implemented yet (lands with lane ${cmd === 'envelope' || cmd === 'bench' ? 'A/B' : 'B'}, P1-P4)`);
      return 2;
    default:
      console.error('usage: node web/src/core/cli.ts selftest [--real] | gen-spec-data | hash <file> | validate <file> | fixture <method>');
      return 2;
  }
}

// exitCode, not process.exit(): exiting early would truncate large stdout writes to a pipe.
main(process.argv.slice(2)).then(
  (code) => {
    process.exitCode = code;
  },
  (e: unknown) => {
    console.error(e);
    process.exitCode = 1;
  },
);
