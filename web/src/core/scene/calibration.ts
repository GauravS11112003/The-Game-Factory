/**
 * Isotonic calibration per grammar rule (§3.3): raw rule confidence → calibrated confidence, so that
 * conf ≥ 0.75 means ≥ 95% precision. `cli.ts calibrate` regenerates TABLES from golden labels; until it has run,
 * every rule uses the identity table, which keeps the base confidences of the §3.3 grammar table.
 * Each table is a list of [raw, calibrated] knots, monotone non-decreasing in both coordinates.
 */
export type RuleId =
  | 'H1' | 'H2' | 'H3' | 'H4' | 'H5' | 'H6' | 'H7' | 'H8' | 'H9' | 'H10' | 'H11' | 'H12' | 'H13' | 'H14' | 'H15'
  | 'H16' | 'H17' | 'H18' | 'H19' | 'H20' | 'H21' | 'H22' | 'STAMP' | 'LABEL' | 'PART';

const IDENTITY: [number, number][] = [
  [0, 0],
  [1, 1],
];

/** GENERATED by `node web/src/core/cli.ts calibrate` (identity until the golden labels are in). */
export const TABLES: Partial<Record<RuleId, [number, number][]>> = {};

export function calibrate(rule: RuleId, raw: number): number {
  const t = TABLES[rule] ?? IDENTITY;
  const x = Math.max(0, Math.min(1, raw));
  if (x <= t[0][0]) return t[0][1];
  for (let i = 1; i < t.length; i++) {
    const [x0, y0] = t[i - 1];
    const [x1, y1] = t[i];
    if (x <= x1) return x1 > x0 ? y0 + ((y1 - y0) * (x - x0)) / (x1 - x0) : y1;
  }
  return t[t.length - 1][1];
}

/** Pool-adjacent-violators fit of (score, correct) pairs into isotonic knots (used by `cli.ts calibrate`). */
export function fitIsotonic(samples: readonly { score: number; correct: boolean }[]): [number, number][] {
  const s = [...samples].sort((a, b) => a.score - b.score);
  const blocks: { x: number; y: number; n: number }[] = [];
  for (const p of s) {
    blocks.push({ x: p.score, y: p.correct ? 1 : 0, n: 1 });
    while (blocks.length > 1 && blocks[blocks.length - 2].y > blocks[blocks.length - 1].y) {
      const b = blocks.pop()!;
      const a = blocks.pop()!;
      const n = a.n + b.n;
      blocks.push({ x: (a.x * a.n + b.x * b.n) / n, y: (a.y * a.n + b.y * b.n) / n, n });
    }
  }
  if (!blocks.length) return IDENTITY;
  return [[0, Math.min(blocks[0].y, 0)], ...blocks.map((b) => [b.x, b.y] as [number, number]), [1, blocks[blocks.length - 1].y]];
}
